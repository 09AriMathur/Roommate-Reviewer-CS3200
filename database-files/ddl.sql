-- Users.TasksCompleted / TasksMissed are denormalised counters, and every
-- completion percentage in the app is derived from them rather than from Tasks.
-- The values inserted above are already the counts of the chore rows below them;
-- this recomputes them anyway, so that editing a chore by hand cannot quietly
-- leave the dashboards lying. PUT and DELETE on /task/tasks/<id> keep them in step
-- from then on.
UPDATE Users u
LEFT JOIN (
    SELECT Assigned_UserID          AS uid,
           SUM(status = 'done')     AS done,
           SUM(status = 'missed')   AS missed
    FROM Tasks
    WHERE Assigned_UserID IS NOT NULL
    GROUP BY Assigned_UserID
) t ON t.uid = u.UserID
SET u.TasksCompleted = COALESCE(t.done, 0),
    u.TasksMissed    = COALESCE(t.missed, 0);
